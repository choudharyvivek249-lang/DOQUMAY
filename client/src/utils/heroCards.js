/** Deterministic pick based on a string seed (e.g. username or room token) */
export function getHeroForSeed(seed = '') {
  if (!seed) return HERO_CARDS[0];
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash * 31 + seed.charCodeAt(i)) & 0xffffffff;
  }
  const idx = Math.abs(hash) % HERO_CARDS.length;
  return HERO_CARDS[idx];
}

/** Pick a random hero different from the current one */
export function getRandomHero(excludeId = '') {
  const pool = HERO_CARDS.filter((h) => h.id !== excludeId);
  return pool[Math.floor(Math.random() * pool.length)] || HERO_CARDS[0];
}
